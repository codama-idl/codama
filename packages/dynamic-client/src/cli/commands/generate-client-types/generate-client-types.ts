import {
    generatePdaTypes,
    generateResolutionInputTypes,
    getResolutionRefs,
} from '@codama/dynamic-address-resolution/codegen';
import { generateSignerTypes, getInstructionSignerRef } from '@codama/dynamic-instructions/codegen';
import { pascalCase, type RootNode } from 'codama';

/**
 * Generate the TypeScript types of a strongly-typed program client for a
 * Codama IDL of the latest major. Use `upgrade` from `@codama/upgrade` first
 * for IDLs of older majors.
 */
export function generateClientTypes(idl: RootNode): string {
    const programName = pascalCase(idl.program.identifier);

    const { mapTypeName: pdasMapTypeName, typeBlock: pdaTypeBlock } = generatePdaTypes(idl);
    const hasPdas = pdasMapTypeName !== null;
    const addressImports = hasPdas ? 'Address, ProgramDerivedAddress' : 'Address';

    let output = `/**
 * Auto-generated types for strongly-typed ProgramClient
 * DO NOT EDIT - Generated by @codama/dynamic-client generate-client-types
 *
 * Note: When the IDL contains types that cannot be resolved (e.g. unsupported
 * kind, missing definition), data types fall back to \`unknown\` instead of
 * \`any\`. Consumers should narrow these values before use.
 */

import type { InstructionNode, RootNode } from 'codama';
import type { ${addressImports} } from '@solana/addresses';
import type { Instruction } from '@solana/instructions';

/**
 * Method builder interface.
 */
export type MethodBuilder<TAccounts, TSigners extends string[]> = {
    accounts(accounts: TAccounts): MethodBuilder<TAccounts, TSigners>;
    signers(signers: TSigners): MethodBuilder<TAccounts, TSigners>;
    instruction(): Promise<Instruction>;
};

`;

    output += generateResolutionInputTypes(idl);
    output += generateSignerTypes(idl);

    const definedTypes = idl.program.definedTypes ?? [];
    for (const ix of idl.program.instructions ?? []) {
        const typeName = pascalCase(ix.identifier);
        const refs = getResolutionRefs(ix, definedTypes);
        const signerRef = getInstructionSignerRef(ix);
        const signersGeneric = signerRef.signersRef ?? 'string[]';

        let dataParam = '';
        if (refs.dataRef) {
            dataParam = refs.hasRequiredData ? `data: ${refs.dataRef}` : `data?: ${refs.dataRef}`;
        }

        const methodSignature = `(${dataParam}) => MethodBuilder<${refs.accountsRef}, ${signersGeneric}>`;
        output += `export type ${typeName}Method = ${methodSignature};\n\n`;
    }

    output += `/**
 * Strongly-typed methods for ${programName}.
 */
export type ${programName}Methods = {\n`;

    for (const ix of idl.program.instructions ?? []) {
        const typeName = pascalCase(ix.identifier);
        output += `    ${ix.identifier}: ${typeName}Method;\n`;
    }

    output += '};\n\n';

    output += pdaTypeBlock;

    const pdasProp = pdasMapTypeName ? `    pdas: ${pdasMapTypeName};\n` : '';
    output += `/**
 * Strongly-typed program client for ${programName}.
 */
export type ${programName}ProgramClient = {
    methods: ${programName}Methods;
${pdasProp}    programAddress: Address;
    root: RootNode;
    instructions: Map<string, InstructionNode>;
};
`;

    return output;
}
